let locale: Locale = systemLocale();
const listeners = new Set<() => void>();

export function systemLocale(): Locale {
  if (typeof navigator === "undefined") {
    return "en";
  }
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export function getLocale(): Locale {
  return locale;
}

export function translate(
  language: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = language === "es" ? es[key] : en[key];
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(vars[name] ?? ""),
  );
}

export function t(
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  return translate(locale, key, vars);
}

export function setLocale(next: Locale): void {
  locale = next;
  for (const listener of listeners) {
    listener();
  }
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function useT(): typeof t {
  useSyncExternalStore(subscribeLocale, getLocale, getLocale);
  return t;
}

export async function loadLocale(): Promise<void> {
  try {
    const store = await load(FILE, { autoSave: false, defaults: {} });
    const saved = await store.get<string>("locale");
    if (saved === "en" || saved === "es") {
      setLocale(saved);
      return;
    }
  } catch {
    // The system language stays.
  }
  setLocale(systemLocale());
}

export async function saveLocale(next: Locale): Promise<void> {
  setLocale(next);
  const store = await load(FILE, { autoSave: false, defaults: {} });
  await store.set("locale", next);
  await store.save();
}

export async function readCursorConnectSeen(): Promise<boolean> {
  try {
    const store = await load(FILE, { autoSave: false, defaults: {} });
    return (await store.get<boolean>("cursorConnectSeen")) === true;
  } catch {
    return false;
  }
}

export async function markCursorConnectSeen(): Promise<void> {
  const store = await load(FILE, { autoSave: false, defaults: {} });
  await store.set("cursorConnectSeen", true);
  await store.save();
}
